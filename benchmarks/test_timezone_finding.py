"""pytest-benchmark suite for the timezone-finding lookup functions.

Each benchmark times one pass over a fixed batch of points (see
`benchmarks/conftest.py`) rather than a single call, so every round performs
identical work and results are comparable across commits.

Benchmark node ids are the join key for the historical trend chart
(.github/workflows/benchmark.yml) - a rename silently orphans that metric's
history. `tests/test_benchmark_names.py` pins the exact expected set of
names collected from this package, so a rename fails loudly instead.
"""

from typing import Callable, Iterable

import pytest

from timezonefinder import TimezoneFinder, TimezoneFinderL

# (fixture_name, in_memory) cases, each with an explicit id - never rely on
# pytest's autogenerated parametrize ids, they break the moment an argument
# type or order changes.
#
# The CI-tracked `benchmark_core` set is one representative headline plus two
# diagnostics. Uniformly random points are the headline because they are the
# only globally representative workload: they contain unique- and
# ambiguous-shortcut points in their real ratio (~25.5% ambiguous, matching
# the shortcut index's `unique surface fraction`), so a change is weighted by
# how much of a real query load it actually helps.
#
# The two per-class cases are tracked alongside it because the headline alone
# cannot attribute a change. An ambiguous lookup costs ~7.4x a unique one, so
# ambiguous work takes ~72% of the wall clock despite being ~25% of the
# queries - meaning a unique-path improvement moves the headline by only
# ~0.28x its true size. The per-class benchmarks show it undiluted.
#
# in_memory only: the file-based mode has its own I/O noise profile and would
# widen the single shared alert threshold for everything.
TIMEZONE_AT_CASES = [
    pytest.param(
        "random_points",
        True,
        id="random-in_memory",
        marks=pytest.mark.benchmark_core,
    ),
    pytest.param("random_points", False, id="random-file_based"),
    pytest.param("on_land_points", True, id="on_land-in_memory"),
    pytest.param("on_land_points", False, id="on_land-file_based"),
    pytest.param(
        "unique_shortcut_points",
        True,
        id="unique_shortcut-in_memory",
        marks=pytest.mark.benchmark_core,
    ),
    pytest.param("unique_shortcut_points", False, id="unique_shortcut-file_based"),
    pytest.param(
        "ambiguous_shortcut_points",
        True,
        id="ambiguous_shortcut-in_memory",
        marks=pytest.mark.benchmark_core,
    ),
    pytest.param(
        "ambiguous_shortcut_points", False, id="ambiguous_shortcut-file_based"
    ),
]

MEMORY_MODES = [
    pytest.param(True, id="in_memory"),
    pytest.param(False, id="file_based"),
]


def _run_over(func: Callable, points: Iterable[tuple[float, float]]) -> None:
    for lng, lat in points:
        func(lng=lng, lat=lat)


@pytest.mark.benchmark
@pytest.mark.parametrize("points_fixture_name, in_memory", TIMEZONE_AT_CASES)
def test_timezone_at(benchmark, request, points_fixture_name, in_memory):
    points = request.getfixturevalue(points_fixture_name)
    tf = TimezoneFinder(in_memory=in_memory)
    benchmark(_run_over, tf.timezone_at, points)


@pytest.mark.benchmark
@pytest.mark.parametrize("in_memory", MEMORY_MODES)
def test_timezone_at_land(benchmark, on_land_points, in_memory):
    tf = TimezoneFinder(in_memory=in_memory)
    benchmark(_run_over, tf.timezone_at_land, on_land_points)


@pytest.mark.benchmark
def test_timezone_at_timezonefinderl(benchmark, ambiguous_shortcut_points):
    # TimezoneFinderL is the shortcut-only heuristic; its accuracy/speed
    # trade-off matters most exactly where shortcuts are ambiguous.
    tf_l = TimezoneFinderL()
    benchmark(_run_over, tf_l.timezone_at, ambiguous_shortcut_points)
