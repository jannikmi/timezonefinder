"""Pin the benchmark names, and the chart labels derived from them.

Two sets of names have to hold still, and both fail silently when they do not.

Node ids are what pytest-benchmark records results under, so a rename (or a
`parametrize` falling back to an autogenerated id) makes every stored report
and every comparison miss the benchmark it used to name.

The *chart labels* are the join key of the historical trend chart
(.github/workflows/benchmark.yml): `scripts/export_timing_chart_json.py` stores
each tracked benchmark under the human-readable label
`scripts/render_benchmark_reports.py` renders in the docs, so changing a label
in that mapping silently starts a brand new metric history beside the orphaned
old one - no error, no warning. A docs-facing wording change is therefore a
history-facing change, which is what pins them here.

This collects `benchmarks/` the same way `make benchmarks` would and compares
the resulting node ids - and the labels they humanize to - against hardcoded
expected sets, so a rename fails this test instead of quietly resetting a
chart.
"""

